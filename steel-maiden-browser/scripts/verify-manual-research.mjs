import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { createManualGraph, expansionChoices, expandManualGraph, layoutManualGraph, visibleManualGraph } from "../app/researchManualGraph.ts";

const data=JSON.parse(await fs.readFile(new URL("../public/data/research-tree.json",import.meta.url),"utf8"));
let graph=createManualGraph(6495);
assert.equal(expansionChoices(data,graph,6495,"down").length,6);
graph=expandManualGraph(data,graph,6495,"down",6444);
assert.deepEqual(graph.ids,[6495,6444],"T-50's other prerequisites must not be automatically inserted");
assert.deepEqual(graph.edges.map((e)=>[e.source,e.target]),[[6495,6444]]);
let layout=layoutManualGraph(graph);
assert.equal(layout.nodes[0].x,layout.nodes[1].x);
assert.ok(layout.nodes[0].y<layout.nodes[1].y);
assert.equal(expandManualGraph(data,graph,6495,"down",6444),graph,"adding the same relationship is idempotent");
assert.equal(expandManualGraph(data,graph,6495,"down",1),graph,"reject arbitrary non-neighbours");
graph=expandManualGraph(data,graph,6495,"down",6823);
graph=expandManualGraph(data,graph,6444,"down",6823);
assert.equal(graph.ids.filter((id)=>id===6823).length,1,"shared targets are a single node");
assert.equal(graph.edges.length,3);
for(const choice of expansionChoices(data,graph,6495,"up"))assert.ok(data.recipes.some((r)=>r.targetId===6495&&r.requirements.some((p)=>p.cardId===choice.node.id)));
layout=layoutManualGraph(graph);
for(const edge of layout.edges)assert.ok(edge.y2>edge.y1,"all arrows point down the real dependency direction");
for(const a of layout.nodes)for(const b of layout.nodes)if(a.id!==b.id)assert.ok(a.x+layout.cardWidth<=b.x||b.x+layout.cardWidth<=a.x||a.y+layout.cardHeight<=b.y||b.y+layout.cardHeight<=a.y,"nodes do not overlap");
const synthetic={nodes:[1,2,3].map((id)=>({id,tank:String(id),person:"",stage:"N1"})),recipes:[{id:"a",targetId:2,requirements:[{cardId:1,generation:1,level:1}]},{id:"b",targetId:1,requirements:[{cardId:2,generation:1,level:1}]}]};
const first=expandManualGraph(synthetic,createManualGraph(1),1,"down",2);
assert.equal(expansionChoices(synthetic,first,2,"down")[0].status,"cycle");
assert.equal(expandManualGraph(synthetic,first,2,"down",1),first);
assert.deepEqual(visibleManualGraph({...data,nodes:data.nodes.filter((n)=>n.id!==6444&&n.id!==6823)},graph).ids,[6495]);
assert.deepEqual(visibleManualGraph({...data,nodes:[]},graph),createManualGraph());
console.log(JSON.stringify({t60Children:6,selectedOnly:true,repeatExpansion:true,sharedNodeDedup:true,cycleGuard:true,layout:true,visibility:true}));

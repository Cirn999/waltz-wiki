const geometry = async () => {
  const failures = await page.evaluate(() => {
    const failures = [];
    if (document.documentElement.scrollWidth > innerWidth + 1) failures.push("horizontal page overflow");
    const note = document.querySelector(".atlas-team-note").getBoundingClientRect();
    const actions = document.querySelector(".atlas-team-actions").getBoundingClientRect();
    if (actions.top - note.bottom > 18) failures.push("team actions inherit global footer spacing");
    const album = document.querySelector(".atlas-album-avatars");
    const team = document.querySelector(".atlas-team");
    const teamRect = team.getBoundingClientRect();
    const resultsRect = document.querySelector(".atlas-results").getBoundingClientRect();
    if (teamRect.bottom > resultsRect.top) failures.push("team panel must be above the avatar list");
    if (Math.abs(teamRect.width - resultsRect.width) > 1) failures.push("team panel must span the list width");
    if (!(team.compareDocumentPosition(album) & Node.DOCUMENT_POSITION_FOLLOWING)) failures.push("team must precede avatars in keyboard/reading order");
    if (getComputedStyle(team).position === "sticky") failures.push("top panel must not obscure the list when scrolling");
    const columns = getComputedStyle(album).gridTemplateColumns.split(" ").length;
    const cards = [...album.querySelectorAll(".atlas-entry")];
    for (let i = 0; i < cards.length; i++) {
      const portrait = cards[i].querySelector(".table-game-avatar").getBoundingClientRect();
      const first = cards[Math.floor(i / columns) * columns].querySelector(".table-game-avatar").getBoundingClientRect();
      if (Math.abs(portrait.top - first.top) > 1) failures.push("avatar alignment");
    }
    for (const wrapper of document.querySelectorAll(".atlas-avatar-picker,.atlas-team-portrait")) {
      const badge = wrapper.querySelector(".atlas-team-toggle");
      if (!badge) continue;
      const rect = badge.getBoundingClientRect();
      const cost = wrapper.querySelector(".table-portrait-cost").getBoundingClientRect();
      if (rect.bottom > cost.top + 1 && rect.left < cost.right && rect.right > cost.left) failures.push("badge obscures cost");
      if (badge.closest("button button")) failures.push("nested button");
    }
    return [...new Set(failures)];
  });
  assert.deepEqual(failures, []);
};

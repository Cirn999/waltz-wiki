import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
import { median } from "../app/attributeChartMath.ts";

const data = JSON.parse(await fs.readFile(new URL("../public/data/maidens.json", import.meta.url), "utf8"));
const allVehicleCount = data.rows.length;
const root = path.join(process.env.LOCALAPPDATA ?? "", "ms-playwright");
const executablePath = (await fs.readdir(root)).filter((name) => name.startsWith("chromium_headless_shell-")).sort().reverse().map((name) => path.join(root, name, "chrome-headless-shell-win64", "chrome-headless-shell.exe"))[0];
const browser = await chromium.launch({ headless: true, executablePath });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.addInitScript(() => {
    window.__chartCopies = [];
    Object.defineProperty(navigator, "clipboard", { configurable: true, value: { write: async (items) => {
      for (const item of items) {
        const blob = await item.getType("image/png"), buffer = await blob.arrayBuffer(), view = new DataView(buffer);
        if (view.getUint32(0) !== 0x89504e47) throw new Error("Not a PNG");
        window.__chartCopies.push({ size: blob.size, width: view.getUint32(16), height: view.getUint32(20) });
      }
    } } });
  });
  await page.goto(process.argv[2] || "http://localhost:3100", { waitUntil: "networkidle" });
  await page.locator(".control-panel .level-picker").getByRole("button", { name: "60级", exact: true }).click();
  const launch = page.locator(".attribute-chart-launchers");
  const location = await launch.boundingBox(), levels = await page.locator(".control-panel .level-picker").boundingBox();
  assert.ok(location.x >= levels.x + levels.width);
  await launch.getByRole("button", { name: "柱状图", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "属性图表", exact: true });
  const candidates = dialog.locator(".ac-candidates"), selected = dialog.locator(".ac-selected");
  const y = dialog.getByRole("region", { name: "Y轴定义", exact: true });
  const generate = () => dialog.getByRole("button", { name: "生成图表 →", exact: true }).click();
  const back = () => dialog.getByRole("button", { name: "← 返回设置", exact: true }).click();
  const openFilters = () => candidates.getByRole("button", { name: /^筛选/ }).click();
  const filter = page.getByRole("dialog", { name: "图表车辆筛选", exact: true });
  assert.equal(await dialog.locator('.ac-levels button[aria-pressed="true"]').innerText(), "60级");
  await openFilters();
  await filter.getByRole("button", { name: "魔改费用筛选", exact: true }).click();
  const cost = page.getByRole("dialog", { name: "魔改费用", exact: true });
  await cost.getByRole("button", { name: "N4-", exact: true }).click();
  await cost.getByRole("button", { name: "确定", exact: true }).click();
  await filter.locator(".filter-confirm").click();
  assert.equal(await candidates.locator(".ac-vehicle").count(), 10);
  await dialog.locator(".ac-import").click();
  assert.equal(await selected.locator(".ac-vehicle").count(), 10);
  assert.equal(await candidates.locator(".ac-vehicle").count(), 0);
  await selected.locator(".ac-vehicle").first().click();
  assert.equal(await candidates.locator(".ac-vehicle").count(), 1);
  await candidates.locator(".ac-vehicle").click();
  await openFilters();
  await filter.getByRole("button", { name: "澳大利亚", exact: true }).click();
  await filter.locator(".filter-confirm").click();
  assert.equal(await selected.locator(".ac-vehicle").count(), 10, "filtering must not erase the comparison cohort");
  await openFilters(); await page.keyboard.press("Escape");
  assert.equal(await filter.count(), 0); assert.equal(await dialog.count(), 1);
  await fs.mkdir(new URL("../.cache", import.meta.url), { recursive: true });
  const screenshot = async (name) => dialog.screenshot({ path: fileURLToPath(new URL(`../.cache/attribute-charts-${name}.png`, import.meta.url)) });
  await screenshot("setup");
  const cohort = data.rows.filter((row) => row.magicCostGroup === "N4-");
  await y.getByRole("button", { name: "选择装甲", exact: true }).click();
  await generate();
  const bars = await dialog.locator(".ac-bar-point").evaluateAll((els) => els.map((el) => ({ id: Number(el.dataset.id), value: Number(el.dataset.value) })));
  assert.deepEqual(bars.map((entry) => entry.value), cohort.map((row) => row.stats[60].armor).sort((a, b) => b - a));
  assert.equal(await dialog.locator(".ac-bar-point image").count(), 10);
  await screenshot("bars");
  await dialog.getByRole("button", { name: "复制图表", exact: true }).click();
  await page.waitForFunction(() => window.__chartCopies.length === 1);
  await back();
  await y.getByRole("button", { name: "计算公式", exact: true }).click();
  await y.getByRole("button", { name: "清空", exact: true }).click();
  for (const name of ["插入(", "插入火力", "插入+", "插入穿甲", "插入)", "插入÷"]) await y.getByRole("button", { name, exact: true }).click();
  await y.getByRole("textbox", { name: "Y轴数字常量" }).fill("2");
  await y.getByRole("button", { name: "插入数字", exact: true }).click();
  await generate();
  const values = await dialog.locator(".ac-bar-point").evaluateAll((els) => els.map((el) => Number(el.dataset.value)));
  assert.deepEqual(values, cohort.map((row) => (row.stats[60].power + row.stats[60].piercing) / 2).sort((a, b) => b - a));
  await back();
  await dialog.locator(".ac-type-switch").getByRole("button", { name: "散点图", exact: true }).click();
  await screenshot("scatter-setup");
  const x = dialog.getByRole("region", { name: "X轴定义", exact: true });
  await x.getByRole("button", { name: "选择火力", exact: true }).click();
  await y.getByRole("button", { name: "单项属性", exact: true }).click();
  await y.getByRole("button", { name: "选择穿甲", exact: true }).click();
  await generate();
  const origin = dialog.locator("[data-median-x]");
  assert.equal(Number(await origin.getAttribute("data-median-x")), median(cohort.map((row) => row.stats[60].power)));
  assert.equal(Number(await origin.getAttribute("data-median-y")), median(cohort.map((row) => row.stats[60].piercing)));
  const scatterValues = await dialog.locator(".ac-scatter-point").evaluateAll((els) => els.flatMap((el) => el.dataset.ids.split(",").map((id) => ({ id: Number(id), x: Number(el.dataset.x), y: Number(el.dataset.y) }))));
  for (const point of scatterValues) { const row = cohort.find((row) => row.id === point.id); assert.equal(point.x, row.stats[60].power); assert.equal(point.y, row.stats[60].piercing); }
  await screenshot("scatter");
  await dialog.getByRole("button", { name: "复制图表", exact: true }).click();
  await page.waitForFunction(() => window.__chartCopies.length === 2);
  await back();
  await y.getByRole("button", { name: "计算公式", exact: true }).click();
  await y.getByRole("button", { name: "清空", exact: true }).click();
  for (const name of ["插入火力", "插入÷", "插入(", "插入命中", "插入-", "插入命中"]) await y.getByRole("button", { name, exact: true }).click();
  assert.equal(await dialog.getByRole("button", { name: "生成图表 →", exact: true }).isDisabled(), true);
  await y.getByRole("button", { name: "插入)", exact: true }).click(); await generate();
  assert.match(await dialog.locator(".ac-setup-footer").innerText(), /10 辆无法计算.*除数为 0/);
  await dialog.locator(".ac-levels").getByRole("button", { name: "99级", exact: true }).click();
  await dialog.getByRole("button", { name: "关闭属性图表", exact: true }).click();
  assert.equal(await page.locator(".control-panel .level-picker button.active").innerText(), "60级");
  assert.equal(await page.locator("tbody tr[data-maiden-id]").count(), allVehicleCount);

  // No artificial cap: all vehicles fit without clipping/overlapping avatars.
  await launch.getByRole("button", { name: "柱状图", exact: true }).click();
  await dialog.locator(".ac-import").click(); await generate();
  assert.equal(await dialog.locator(".ac-bar-point").count(), allVehicleCount);
  const positions = await dialog.locator(".ac-bar-point clipPath circle").evaluateAll((els) => els.map((el) => ({ x: Number(el.getAttribute("cx")), radius: Number(el.getAttribute("r")) })));
  positions.forEach((point, i) => { if (i) assert.ok(point.x - positions[i - 1].x > point.radius + positions[i - 1].radius + 4); });
  assert.ok(Number(await dialog.locator("svg.ac-chart-svg").getAttribute("width")) > 40000);
  await dialog.getByRole("button", { name: "复制图表", exact: true }).click();
  await page.waitForFunction(() => window.__chartCopies.length === 3, null, { timeout: 60000 });
  const copies = await page.evaluate(() => window.__chartCopies);
  assert.ok(copies[2].width > 20000 && copies[2].width <= 30000 && copies.every((copy) => copy.size > 10000));
  await back();
  await dialog.locator(".ac-type-switch").getByRole("button", { name: "散点图", exact: true }).click();
  for (const axis of ["X", "Y"]) {
    const editor = dialog.getByRole("region", { name: `${axis}轴定义`, exact: true });
    await editor.getByRole("button", { name: "计算公式", exact: true }).click();
    await editor.getByRole("button", { name: "清空", exact: true }).click();
    await editor.getByRole("textbox", { name: `${axis}轴数字常量` }).fill("1");
    await editor.getByRole("button", { name: "插入数字", exact: true }).click();
  }
  await generate();
  assert.equal(await dialog.locator(".ac-scatter-point").count(), 1);
  assert.equal((await dialog.locator(".ac-scatter-point").getAttribute("data-ids")).split(",").length, allVehicleCount);
  assert.equal(await origin.getAttribute("data-median-x"), "1");
  await dialog.locator(".ac-scatter-point").click();
  assert.equal(await dialog.locator(".ac-point-readout b").count(), allVehicleCount);
  assert.equal(await dialog.locator(".ac-chart-svg").evaluate((el) => /NaN|Infinity/.test(el.outerHTML)), false);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await dialog.evaluate((el) => el.scrollWidth > el.clientWidth + 1), false);
  await back();
  await dialog.locator(".ac-mobile-columns").getByRole("button", { name: "坐标定义", exact: true }).click();
  assert.equal(await dialog.locator(".ac-definitions").isVisible(), true);
  assert.equal(await dialog.locator(".ac-selected").isVisible(), false);
  await dialog.locator(".ac-mobile-columns").getByRole("button", { name: /^待比较/ }).click();
  assert.equal(await dialog.locator(".ac-selected").isVisible(), true);
  await screenshot("mobile");
  assert.equal(await dialog.evaluate((el) => el.scrollWidth > el.clientWidth + 1), false);
  await page.keyboard.press("Escape");
  assert.equal(await dialog.count(), 0);
  assert.equal(await page.evaluate(() => document.body.style.overflow), "");
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ selectedCohort: 10, allVehicles: allVehicleCount, clipboardPngs: copies, errors, tested: "filters, selection, formula, true coordinates, medians, overlap groups, all-vehicle export, independent level/filter, mobile" }));
} finally { await browser.close(); }
